experiment_id = experiment.experiment_id

# 3. Pull all completed tracking runs
runs_df = mlflow.search_runs(experiment_ids=[experiment_id])

# Format: df = df[df['column_name'] != value]
# The ~ operator means "NOT", filtering out the matching run IDs cleanly
runs_df = runs_df[~runs_df['run_id'].isin(['1ed512ef4f2049088095c48243a4a13d','747880fe06594e7f9016ef52b8eb9196','61550c12d7164885b601d95f6e018886','66d134f539cd460798183cb81838f4ce', '0e8b4d3b21884d52a232b14f569c5b6b','b59326483e96405ea0378366557dc72c','8878ad09bbca43488401b875a92b89ae'])]

